def _parse(raw):
    rows = raw.split()
    rows += ["....."] * (GLYPH_H - len(rows))
    for row in rows:
        assert len(row) == GLYPH_W, f"linha com largura errada: {row!r}"
    return rows


GLYPHS = {ch: _parse(raw) for ch, raw in _RAW.items()}


def text_width(text, scale):
    """Largura em px do texto, sem a coluna de espaço depois do último glifo."""
    if not text:
        return 0
    return (len(text) * ADVANCE - 1) * scale


def text(s, x, y, scale, color):
    """Desenha `s` com o canto superior esquerdo em (x, y).

    Pixels vizinhos na mesma linha viram um único <rect>, o que corta o
    tamanho do SVG em várias vezes.
    """
    rects = []
    for i, ch in enumerate(s):
        rows = GLYPHS.get(ch, GLYPHS["?"])
        gx = x + i * ADVANCE * scale
        for r, row in enumerate(rows):
            c = 0
            while c < GLYPH_W:
                if row[c] != "#":
                    c += 1
                    continue
                start = c
                while c < GLYPH_W and row[c] == "#":
                    c += 1
                rects.append(
                    f'<rect x="{gx + start * scale}" y="{y + r * scale}" '
                    f'width="{(c - start) * scale}" height="{scale}"/>'
                )
    return f'<g fill="{color}">{"".join(rects)}</g>'
